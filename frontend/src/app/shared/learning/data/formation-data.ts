function lesson(
  courseId: string,
  order: number,
  title: string,
  objective: string,
  extra?: Partial<Lesson>,
): Lesson {
  const id = `${courseId}-l${order}`;
  return {
    id,
    courseId,
    order,
    title,
    durationMinutes: extra?.durationMinutes ?? 25,
    objective,
    sections: extra?.sections ?? [
      { title: 'Introduction', body: objective },
      { title: 'Concepts clés', body: `Approfondissez « ${title} » dans le contexte du trading crypto simulé sur CryptoTrade.` },
      { title: 'Application', body: 'Appliquez ces notions sur le graphique BTC/USDT et validez avec le mini quiz de fin de leçon.' },
    ],
    conceptCard: extra?.conceptCard ?? {
      title: 'À retenir',
      body: `${title} est une brique essentielle pour progresser vers un trading discipliné.`,
    },
    practicalExample: extra?.practicalExample,
    takeaways: extra?.takeaways ?? [
      'Reliez la théorie à la simulation CryptoTrade.',
      'Notez vos erreurs dans un journal de trading.',
      'Passez le quiz associé au module pour valider vos acquis.',
    ],
    knowledgeCheck: extra?.knowledgeCheck ?? {
      question: `Quelle est la meilleure approche après « ${title} » ?`,
      options: [
        'Trader immédiatement avec effet de levier maximal',
        'Tester en simulation avec un plan et une taille de position',
        'Ignorer la gestion des risques',
        'Suivre uniquement les réseaux sociaux',
      ],
      correctIndex: 1,
      explanation: 'La simulation avec plan et sizing est la voie la plus sûre pour apprendre.',
    },
    mission: extra?.mission,
  };
}

